function strikeWeight(t: number, impact: number): number {
  if (t < 8.615) return impact * .72;
  if (t >= 43.566) return impact * .64;
  const light = t >= 34.778 ? .57 : .70;
  return impact * (light + (1 - light) * impact);
}

